import csv

def generate_circuit_csv(output_file="circuit.csv"):

    with open(output_file, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["segment", "latitude", "longitude"])

        for segment, coords in zones.items():
            for lat, lon in coords:
                writer.writerow([segment, lat, lon])

    print(f"CSV généré : {output_file}")


# Exemple d'utilisation :
